import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const source=fs.readFileSync("assets/budget-planner.js","utf8");
const initial={customers:"8",qualifiedRate:"40",closeRate:"10",cpl:"400",fees:"14000",contribution:"20000"};
const inputs=Object.fromEntries(Object.entries(initial).map(([k,v])=>[k,{value:v}]));
const ids=["qualified","leads","spend","total","break-even","headroom"];
const results=Object.fromEntries(ids.map(k=>["#budget-"+k,{textContent:"—"}]));
const events={};
const form={elements:{namedItem:k=>inputs[k]},addEventListener:(n,fn)=>events["form:"+n]=fn};
const reset={addEventListener:(n,fn)=>events["reset:"+n]=fn};
const doc={querySelector:s=>s==="#budget-planner-form"?form:s==="#budget-reset"?reset:s==="#budget-error"?error:results[s],addEventListener:(n,fn)=>{if(n==="DOMContentLoaded")fn();}};
const error={textContent:""};
vm.runInNewContext(source,{document:doc,Intl,Number,Object,Math,console});
const check=(id,val)=>assert.ok(results["#budget-"+id].textContent.includes(val),id+": expected "+val+" got "+results["#budget-"+id].textContent);
