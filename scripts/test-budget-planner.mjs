inputs.closeRate.value="10";inputs.customers.value="1.5";events["form:input"]();assert.notEqual(error.textContent,"");
inputs.customers.value="1";inputs.qualifiedRate.value="100";inputs.closeRate.value="100";inputs.cpl.value="0";inputs.fees.value="0";inputs.contribution.value="0";events["form:input"]();assert.equal(error.textContent,"");check("qualified","1");check("total","0");
inputs.customers.value="-1";events["form:input"]();assert.notEqual(error.textContent,"");
events["reset:click"]();assert.equal(error.textContent,"");check("leads","200");check("headroom","66,000");
assert.equal(source.includes("fetch("),false);
assert.equal(source.includes("localStorage"),false);
console.log("Budget planner smoke test passed: reverse funnel, cost/headroom, invalid rates, zero cost, reset and browser-only inputs.");
