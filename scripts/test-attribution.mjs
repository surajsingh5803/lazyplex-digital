import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const src=fs.readFileSync("assets/main.js","utf8");
const saved=new Map();
const storage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)};
const listeners={};
const location={search:"?utm_source=Google&utm_medium=CPC&utm_campaign=Brand_Search",href:"https://digital.lazyplex.com/services/google-ads-ppc/",origin:"https://digital.lazyplex.com",pathname:"/services/google-ads-ppc/"};
const win={location,sessionStorage:storage,dataLayer:[]};
const doc={querySelector:()=>null,addEventListener:(event,fn)=>listeners[event]=fn};
vm.runInNewContext(src,{window:win,document:doc,URLSearchParams,URL,Date,Number,Object,JSON,console});
const stored=JSON.parse(saved.get("lazyplex_campaign_session"));
assert.equal(stored.utm_source,"google");
assert.equal(stored.utm_medium,"cpc");
assert.equal(stored.utm_campaign,"brand_search");
listeners.click({target:{closest:()=>({getAttribute:()=>"/contact/?service=google-ads-ppc"})}});
assert.equal(win.dataLayer[0].event,"lazyplex_contact_cta_click");
assert.equal(win.dataLayer[0].service,"google-ads-ppc");

let submit;
const status={textContent:"",className:""};
const context={textContent:"",hidden:true};
const service={value:"lead-generation",selectedIndex:0,options:[{value:"lead-generation",text:"Lead Generation"}]};
const industry={value:"Healthcare",options:[{value:"Healthcare",text:"Healthcare"}]};
const inputs={service,industry};
const form={elements:{namedItem:key=>inputs[key]},reportValidity:()=>true,addEventListener:(event,fn)=>{if(event==="submit")submit=fn;}};
const location2={search:"?service=lead-generation&source=service-detail",href:"https://digital.lazyplex.com/contact/?service=lead-generation&source=service-detail",origin:"https://digital.lazyplex.com",pathname:"/contact/",assign:url=>{location2.assigned=url;}};
const win2={location:location2,sessionStorage:storage,dataLayer:[]};
const doc2={querySelector:s=>s==="#enquiry-form"?form:s==="#form-status"?status:s==="#enquiry-context"?context:null,addEventListener:()=>{}};
class FakeFormData { get(key){return ({name:"Sample Contact",phone:"9876543210",email:"customer@example.com",company:"Example",industry:"Healthcare",budget:"Not specified",message:"SEO assessment"})[key] || "";} }
vm.runInNewContext(src,{window:win2,document:doc2,URLSearchParams,URL,Date,Number,Object,JSON,FormData:FakeFormData,console});
assert.equal(typeof submit,"function");
submit({preventDefault(){}});
const draft=new URL(location2.assigned).searchParams.get("text");
assert.ok(draft.includes("Campaign source: google"),draft);
assert.ok(draft.includes("Campaign medium: cpc"),draft);
assert.ok(draft.includes("Campaign label: brand_search"),draft);
assert.ok(draft.includes("Page source: service-detail"),draft);
assert.equal(win2.dataLayer[0].event,"lazyplex_whatsapp_handoff");
assert.equal(win2.dataLayer[0].utm_source,"google");
assert.equal(win2.dataLayer[0].utm_medium,"cpc");
assert.equal("name" in win2.dataLayer[0],false);
assert.equal("phone" in win2.dataLayer[0],false);
